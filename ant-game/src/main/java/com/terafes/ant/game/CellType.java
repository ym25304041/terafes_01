package com.terafes.ant.game;

/**
 * マス目1つ分の「地形」の種類です。
 *
 * 敵やアイテムは地形とは別のデータ（レイヤー）として後から追加する予定のため、
 * ここには地形だけを定義しています。
 * こうしておくと「壁の上に敵がいる」のような矛盾を避けやすく、拡張もしやすくなります。
 */
public enum CellType {

    /** 道: 移動できるマス */
    ROAD,
    /** 壁: 移動できないマス */
    WALL,
    /** 落とし穴: 通常移動で入るとゲームオーバー。ジャンプで飛び越えられる */
    PIT,
    /** ゴール: 到達するとクリア */
    GOAL
}
