package com.terafes.ant.game;

/**
 * マス目1つ分の「地形」の種類です。
 *
 * アイテム（物資・武器）や敵は地形とは別のデータ（レイヤー）として扱います。
 * 「壁の上に敵がいる」のような矛盾を避けやすく、拡張もしやすくなります。
 */
public enum CellType {

    /** 道: 移動できるマス */
    ROAD,
    /** 壁: 移動できないマス */
    WALL,
    /** 落とし穴: 通常移動で入るとゲームオーバー。ジャンプで飛び越えられる */
    PIT,
    /** ゴール: 到達するとクリア */
    GOAL,
    /** スイッチ: 物資を持って乗ると物資を消費し、同じ記号のドアを開く。通行はできる */
    SWITCH,
    /** ドア: 閉じている間は通れない。対応するスイッチが作動すると開いて通れる */
    DOOR
}
